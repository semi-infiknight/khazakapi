    authDetails,
    copyable: false,
    pricing,
    docs,
    baseUrl,
    frequency: null,
    coverage,
    freshness: { label: "SEE DOCS", tone: "none" },
    likes: 0,
    note,
    trust: trust ?? commercialTrust(provider, sourceUrl, auth === "oauth" ? "oauth" : auth === "token" ? "token" : "apiKey"),
